# ----------------------------------------------------------------------------
# DSL → JSON 编译器
# ----------------------------------------------------------------------------

def compile_phases_to_transitions(phases_meta: dict) -> dict:
    """phases.yaml → phase-transitions.json 等价对象。

    输出含 ``$generatedFrom`` / ``$doNotEdit`` sentinel 字段，明示该对象由 DSL 编译产出。
    sentinel 字段不参与 ``_diff_objects`` 等价性比较（见 ``SENTINEL_FIELDS``）。
    """
    phases_list = phases_meta.get("phases", [])
    rules = phases_meta.get("rules", {})

    transitions = {}
    for p in phases_list:
        transitions[p["id"]] = {
            "next": p.get("next"),
            "canSkipTo": p.get("canSkipTo"),
        }

    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$generatedFrom": "meta/phases.yaml",
        "$doNotEdit": "Auto-generated by scripts/render_artifacts.py from meta/phases.yaml. Edit the YAML source then run `python3 scripts/render_artifacts.py --write-json --write`.",
        "title": "PhaseTransitions",
        "description": "合法的阶段流转映射表（唯一权威来源）。编排器在每次更新 currentPhase 前，MUST 查此表确认新阶段是当前阶段的合法后继。",
        "transitions": transitions,
        "rules": {
            "forward": rules.get("forward", ""),
            "skipCondition": rules.get("skipCondition", ""),
            "rollback": rules.get("rollback", ""),
            "termination": rules.get("termination", ""),
        },
    }


def compile_state_schema(state_meta: dict) -> dict:
    """state-schema.yaml → state-schema.json 等价对象。

    剔除以 ``$comment`` 开头的元数据字段（YAML 注释，不属于 JSON Schema），
    并在 ``$schema`` 之后插入 ``$generatedFrom`` / ``$doNotEdit`` sentinel。
    """
    out: dict = {}
    inserted_sentinel = False
    for k, v in state_meta.items():
        if k.startswith("$comment"):
            continue
        out[k] = v
        # 在 $schema 之后立即插入 sentinel
        if k == "$schema" and not inserted_sentinel:
            out["$generatedFrom"] = "meta/state-schema.yaml"
            out["$doNotEdit"] = (
                "Auto-generated by scripts/render_artifacts.py from meta/state-schema.yaml. "
                "Edit the YAML source then run `python3 scripts/render_artifacts.py --write-json --write`."
            )
            inserted_sentinel = True
    # 若没有 $schema 字段（极罕见），把 sentinel 放最前
    if not inserted_sentinel:
        sentinel = {
            "$generatedFrom": "meta/state-schema.yaml",
            "$doNotEdit": "Auto-generated by scripts/render_artifacts.py.",
        }
        out = {**sentinel, **out}
    return out


# Sentinel 字段集（_diff_objects 比较时跳过）
SENTINEL_FIELDS = {"$generatedFrom", "$doNotEdit"}


# ----------------------------------------------------------------------------
# A. DSL 内部一致性
# ----------------------------------------------------------------------------

def check_dsl_internal(meta: dict) -> CheckResult:
    check = CheckResult(
        check_id="dsl-internal",
        description="DSL 内部一致性（meta/ 各文件相互引用合法）",
    )

    phases = meta.get("phases")
    state_schema = meta.get("state_schema")
    commands = meta.get("commands")

    if phases is None:
        check.findings.append(Finding(
            check_id=check.check_id, severity=Severity.WARN,
            title="meta/phases.yaml 不存在",
            fix_hint="运行 python3 scripts/seed_meta_from_existing.py --write",
        ))
        return check

    # A1: phases 内部 — id 唯一
    phase_list = phases.get("phases", [])
    ids = [p.get("id") for p in phase_list]
    seen = set()
    for pid in ids:
        if pid in seen:
            check.findings.append(Finding(
                check_id=check.check_id, severity=Severity.FAIL,
                title=f"phases.yaml 中 id '{pid}' 重复",
                file=str(paths.to_relative(paths.META_PHASES)),
            ))
        seen.add(pid)

    # A2: phases — next / canSkipTo 引用合法
    id_set = set(ids)
    for p in phase_list:
        for slot in ("next", "canSkipTo"):
            v = p.get(slot)
            if v is None:
                continue
            if v not in id_set:
                check.findings.append(Finding(
                    check_id=check.check_id, severity=Severity.FAIL,
                    title=f"phases.yaml 中 '{p.get('id')}' 的 {slot}='{v}' 不在 id 集合内",
                    file=str(paths.to_relative(paths.META_PHASES)),
                ))

    # A3: state-schema PhaseId enum 与 phases.yaml id 集合一致
    if state_schema is not None:
        defs = state_schema.get("definitions", {})
        phase_id_def = defs.get("PhaseId", {})
        enum_ids = set(phase_id_def.get("enum", []))
        only_phases = id_set - enum_ids
        only_schema = enum_ids - id_set
        for pid in sorted(only_phases):
            check.findings.append(Finding(
                check_id=check.check_id, severity=Severity.FAIL,
                title=f"phases.yaml 中 '{pid}' 缺失于 state-schema.yaml#definitions.PhaseId.enum",
                file=str(paths.to_relative(paths.META_STATE_SCHEMA)),
            ))
        for pid in sorted(only_schema):
            check.findings.append(Finding(
                check_id=check.check_id, severity=Severity.FAIL,
                title=f"state-schema.yaml#definitions.PhaseId.enum 中 '{pid}' 缺失于 phases.yaml",
                file=str(paths.to_relative(paths.META_PHASES)),
            ))

    # A4: commands.yaml 的 file 路径实际存在
    if commands is not None:
        for c in commands.get("commands", []):
            file_rel = c.get("file")
            if not file_rel:
                check.findings.append(Finding(
                    check_id=check.check_id, severity=Severity.WARN,
                    title=f"commands.yaml 中 '{c.get('name')}' 缺少 file 字段",
                ))
                continue
            file_abs = paths.CLAUDE_ROOT / file_rel
            if not file_abs.is_file():
                check.findings.append(Finding(
                    check_id=check.check_id, severity=Severity.FAIL,
                    title=f"commands.yaml 中 '{c.get('name')}' 引用的文件不存在：{file_rel}",
                    fix_hint="检查 file 字段或确认命令文件存在于 .claude/commands/",
                ))

    if not check.findings:
        check.findings.append(Finding(
            check_id=check.check_id, severity=Severity.PASS,
            title=f"DSL 内部一致性通过（{len(id_set)} 阶段，"
                  f"{len(commands.get('commands', []) if commands else [])} 命令）",
        ))
    return check


