# B. DSL → JSON 等价性（canonical-equal）
# ----------------------------------------------------------------------------

def check_phases_equivalence(meta: dict) -> CheckResult:
    check = CheckResult(
        check_id="dsl-phases-equiv",
        description="phases.yaml 编译产出 ↔ phase-transitions.json 对象树等价",
    )
    phases = meta.get("phases")
    if phases is None:
        check.findings.append(Finding(
            check_id=check.check_id, severity=Severity.WARN,
            title="phases.yaml 不存在，跳过等价性校验",
        ))
        return check

    if not paths.PHASE_TRANSITIONS.is_file():
        check.findings.append(Finding(
            check_id=check.check_id, severity=Severity.FAIL,
            title="phase-transitions.json 不存在",
            file=str(paths.to_relative(paths.PHASE_TRANSITIONS)),
        ))
        return check

    compiled = compile_phases_to_transitions(phases)
    actual = json.loads(paths.PHASE_TRANSITIONS.read_text(encoding="utf-8"))

    diffs = _diff_objects(compiled, actual)
    if diffs:
        for path, msg in diffs[:10]:
            check.findings.append(Finding(
                check_id=check.check_id, severity=Severity.FAIL,
                title=f"对象树差异：{path}",
                message=msg,
                fix_hint="改 phases.yaml 或与 phase-transitions.json 对齐",
            ))
        if len(diffs) > 10:
            check.findings.append(Finding(
                check_id=check.check_id, severity=Severity.INFO,
                title=f"...省略 {len(diffs) - 10} 处差异",
            ))
    else:
        check.findings.append(Finding(
            check_id=check.check_id, severity=Severity.PASS,
            title="phases.yaml 与 phase-transitions.json 对象树等价",
        ))
    return check


