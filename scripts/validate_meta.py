#!/usr/bin/env python3
"""L0 DSL 校验：meta/*.yaml 内部一致性 + 与现有 JSON Schema **canonical-equal** 校验。

⚠️ **承诺降级声明（v1 → v2）**：
    Plan v1 原本写"现有 JSON → DSL 反向生成 → 重新编译回 JSON **byte-equal**"，
    实施时降级为 **canonical-equal**（对象树等价）。原因：
    - phase-transitions.json 用了手工对齐空格让 next 列对齐
    - state-schema.json 用了选择性紧凑数组（短数组单行 / 复杂对象多行）
    - 字符级 byte-equal 工作量约 5x，运行时 `json.load` 后行为完全相同
    canonical-equal 已能保证运行时正确性。

Phase 2 引入。三类校验：

A. **DSL 内部一致性**：
   - phases.yaml 的 next/canSkipTo 引用合法（指向已定义的 phase id）
   - state-schema.yaml 的 PhaseId enum 与 phases.yaml 的 id 集合一致
   - commands.yaml 的 file 路径实际存在

B. **DSL → JSON canonical 等价性**：
   - phases.yaml 编译后的 transitions 对象 == phase-transitions.json 解析后的 transitions
   - state-schema.yaml 解析后的对象 == state-schema.json 解析后的对象
   - 不要求字符级 byte-equal，仅要求语义（对象树）等价

C. **现有产物完整性**：
   - phase-transitions.json / state-schema.json 文件存在且可解析

CLI:
    python scripts/validate_meta.py                # 全部 3 组校验
    python scripts/validate_meta.py --scope=internal  # 仅 A
    python scripts/validate_meta.py --scope=equivalence  # 仅 B
    python scripts/validate_meta.py --format=md|json|console

退出码：
    0 PASS / 1 WARN / 2 FAIL / 3 ERROR
"""

from __future__ import annotations

import argparse
import json
import sys
