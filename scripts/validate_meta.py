# ----------------------------------------------------------------------------
# Object diff（深度对比，含路径）
# ----------------------------------------------------------------------------

def _diff_objects(a, b, path: str = "$") -> list[tuple[str, str]]:
    """深度对比两个对象。返回 [(path, message)]。

    忽略 ``SENTINEL_FIELDS`` 中的字段（如 ``$generatedFrom`` / ``$doNotEdit``），
    因为它们是元数据声明，与运行时语义无关。
    """
    out: list[tuple[str, str]] = []
    if type(a) != type(b):
        out.append((path, f"类型不同: {type(a).__name__} vs {type(b).__name__}"))
        return out
    if isinstance(a, dict):
        # 剔除 sentinel 字段后再比对
        ka = {k for k in a.keys() if k not in SENTINEL_FIELDS}
        kb = {k for k in b.keys() if k not in SENTINEL_FIELDS}
        only_a = ka - kb
        only_b = kb - ka
        for k in sorted(only_a):
            out.append((f"{path}.{k}", f"DSL 多出键: {k}"))
        for k in sorted(only_b):
            out.append((f"{path}.{k}", f"JSON 多出键: {k}"))
        for k in sorted(ka & kb):
            out.extend(_diff_objects(a[k], b[k], f"{path}.{k}"))
    elif isinstance(a, list):
        if len(a) != len(b):
            out.append((path, f"列表长度不同: {len(a)} vs {len(b)}"))
            return out
        for i, (xa, xb) in enumerate(zip(a, b)):
            out.extend(_diff_objects(xa, xb, f"{path}[{i}]"))
    else:
        if a != b:
            sa = repr(a)[:60]
            sb = repr(b)[:60]
            out.append((path, f"值不同: DSL={sa}  JSON={sb}"))
    return out


# ----------------------------------------------------------------------------
# 入口
# ----------------------------------------------------------------------------

DIMENSIONS = {
    "internal": [check_dsl_internal],
    "equivalence": [check_phases_equivalence, check_state_schema_equivalence],
}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="validate_meta",
        description="ai-team meta/ DSL 校验（Phase 2）",
    )
    ap.add_argument("--scope", default="all",
                    choices=["all", "internal", "equivalence"])
    ap.add_argument("--format", default="console", choices=["console", "md", "json"])
    args = ap.parse_args(argv)

    try:
        meta = meta_loader.load_all()
    except Exception as e:
        print(f"加载 meta/*.yaml 失败：{type(e).__name__}: {e}", file=sys.stderr)
        return 3

    report = Report(title="DSL 校验报告（Phase 2）")
    selected: list = []
    if args.scope in ("all", "internal"):
        selected.extend(DIMENSIONS["internal"])
    if args.scope in ("all", "equivalence"):
        selected.extend(DIMENSIONS["equivalence"])

    for fn in selected:
        try:
            report.checks.append(fn(meta))
        except Exception as e:
            c = CheckResult(check_id=fn.__name__, description=f"({fn.__name__})")
            c.findings.append(Finding(
                check_id=fn.__name__, severity=Severity.ERROR,
                title=f"维度执行异常：{type(e).__name__}",
                message=str(e),
            ))
            report.checks.append(c)

    report.summary = {
        "phases_yaml": "loaded" if meta["phases"] else "missing",
        "state_schema_yaml": "loaded" if meta["state_schema"] else "missing",
        "commands_yaml": "loaded" if meta["commands"] else "missing",
        "scope": args.scope,
    }
    return reporters.emit(report, fmt=args.format)


if __name__ == "__main__":
    sys.exit(main())
